import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ channel: 'msedge', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
await p.goto('http://localhost:5173/');
await p.waitForTimeout(2500);
await p.click('#start-btn');
await p.waitForTimeout(2500);
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
console.log('預設:', await p.textContent('#vol-val'));
await p.fill('#vol', '30');
await p.dispatchEvent('#vol', 'input');
console.log('調整後:', await p.textContent('#vol-val'), 'localStorage:', await p.evaluate(() => localStorage.getItem('xiawei-birthday-volume')));
await p.screenshot({ path: out });
await p.reload();
await p.waitForTimeout(2500);
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
console.log('重新整理後:', await p.textContent('#vol-val'));
await b.close();
